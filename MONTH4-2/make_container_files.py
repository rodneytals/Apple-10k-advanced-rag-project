"""
make_container_files.py -- Day 19 (Day 20: also copies monitoring.py): write Dockerfile, docker-compose.yml, .dockerignore and the health check.

    written = make_container_files("rag_pipeline", ".", check_report, requirements_report)

Nothing here needs a secret: the image contains code and packages only. Passwords and keys reach the container at
run time through your .env file (compose "env_file"), and .env itself is never copied into the image.
Files that already exist are kept as <name>.previous before being overwritten.
"""
import os
