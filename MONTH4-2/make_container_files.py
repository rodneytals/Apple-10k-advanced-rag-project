def make_container_files(package: str, project_dir: str, check, reqs, host_port: int = 8080) -> List[str]:
    pipeline_path = os.path.join(project_dir, package, "pipeline.py")
    source = open(pipeline_path, encoding="utf-8").read()
    state_dirs = sorted({v for v in check.volume_paths if "/" not in v and not v.lower().endswith((".db", ".sqlite", ".sqlite3"))})
    bare_files = [v for v in check.volume_paths if v.lower().endswith((".db", ".sqlite", ".sqlite3")) and "/" not in v]
    problems = []
    if bare_files:
        problems.append(f"state file(s) {bare_files} sit in the project root: a file cannot be a volume. Move them into a folder "
                        f"(for example checkpoints/) in the code, freeze again, and re-run this.")
    if problems:
        raise RuntimeError("; ".join(problems))
    # Day 20: monitoring.py goes into the image when it sits next to serve.py (serve.py imports it if it is there)
    extra_app = [f for f in OPTIONAL_APP_FILES if os.path.exists(os.path.join(project_dir, f))]
    files: Dict[str, str] = {
        "Dockerfile": dockerfile_text(package, reqs.python_version, bool(reqs.torch_pins), check.copy_paths, state_dirs, extra_app),
        ".dockerignore": dockerignore_text(package, check.copy_paths, extra_app),
        "docker-compose.yml": compose_text(check.redis_mode, redis_environment(source), state_dirs, host_port,
                                           door=os.path.exists(os.path.join(project_dir, "Caddyfile")),
                                           watchdog=all(os.path.exists(os.path.join(project_dir, f)) for f in WATCHDOG_FILES)),
    }
    written = []
    for name, text in files.items():
        _backup_write(os.path.join(project_dir, name), text)
        written.append(name)
    hc = os.path.join(project_dir, "docker_healthcheck.py")
    if os.path.abspath(os.path.join(HERE, "docker_healthcheck.py")) != os.path.abspath(hc):
        shutil.copyfile(os.path.join(HERE, "docker_healthcheck.py"), hc)
    written.append("docker_healthcheck.py")
    return written
