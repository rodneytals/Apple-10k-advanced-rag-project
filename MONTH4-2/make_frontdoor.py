"""
make_frontdoor.py -- Day 21: the front door (a small Caddy proxy in front of the API).

    python make_frontdoor.py                  # writes ./Caddyfile  (the old one is kept as Caddyfile.previous)

Why a door at all? The API itself has routes only YOU should reach: /metrics, /readyz (names your databases), /statusz.
The door is a short allow-list. Exactly two things get through, nothing else:

    POST /ask        -> the API       (the question endpoint; the API still checks the key)
    GET  /healthz    -> the API       (HEAD is turned into GET, so uptime services that use HEAD work too)

Everything else, in any spelling (/Metrics, //metrics, /%6Detrics, /ask/../metrics ...), is answered with 404 by the door itself
and never reaches the API. The match is on the DECODED path and is exact (no wildcards, case-sensitive): a path is let through
only if it is exactly "/ask" or "/healthz" after the browser-style decoding the API would do as well.

What else the door does:
  * limits the request body to 20 KB (it answers 413 and the API never reads more than that; chunked bodies too: the API's own check only looks at the declared size),
  * ends slow connections (a client that dribbles its request in, one byte at a time, cannot hold a connection forever),
  * removes the "Server:" header, adds no-store / nosniff,
  * gives every request one id (X-Request-ID, passed to the API, which logs it) and writes the same id in its own log,
  * logs one JSON line per request WITHOUT any request header (X-API-Key is a header: it must never reach a log).
"""
import os
import shutil
import sys
from typing import List, Optional

CADDY_IMAGE = "caddy:2-alpine"
ALLOWED = (("POST", "/ask"), ("GET", "/healthz"))          # the whole allow-list; HEAD /healthz is accepted too (see below)

# Spellings somebody might try to reach a closed route with. Shared by the tests and by check_launch.py (which sends every one
# of them through the real door with your real keys and expects 404 each time). Percent-encoded only: no raw control characters.
CLOSED_PATHS: List[str] = [
    "/metrics", "/metrics/", "/Metrics", "/METRICS", "//metrics", "/./metrics", "/metrics?x=1", "/metrics;x=1",
    "/%6Detrics", "/%6detrics", "/m%65trics", "/%2e/metrics", "/%2E%2E/metrics", "/%252e%252e/metrics",
    "/ask/../metrics", "/healthz/../metrics", "/healthz/..%2fmetrics", "/healthz%2f..%2fmetrics", "/ask%2f..%2fmetrics",
    "/healthz;/../metrics", "/healthz/;/metrics", "/metrics%00", "/metrics%2f", "/metrics%20", "/metrics%09", "/metrics%0d%0a",
    "/readyz", "/readyz/", "/statusz", "/docs", "/redoc", "/openapi.json", "/docs/oauth2-redirect",
    "/", "/.env", "/admin", "/robots.txt", "/favicon.ico", "/healthz/", "/healthz/x", "/ask/", "/ask/x",
    "/Ask", "/ASK", "/HEALTHZ", "/Healthz", "//ask", "//healthz", "/./ask", "/./healthz", "/ask%00", "/healthz%00",
]


def caddyfile_text(upstream: str = "rag:8000", address: str = ":8080", max_body: str = "20KB",
                   read_header: str = "10s", read_body: str = "30s", idle: str = "2m", write: str = "3m",
                   upstream_wait: str = "160s") -> str:
    """The Caddyfile. `address` ':8080' = plain HTTP inside the compose network (the tunnel or your own HTTPS front sits outside).
    A host name instead ('api.example.com') makes Caddy get a real certificate by itself (needs ports 80 and 443 reachable)."""
    plain = address.startswith(":") or address.startswith("http://")
    tls = "\tauto_https off\n" if plain else ""
    return f'''# Generated by make_frontdoor.py (Day 21). Do not put secrets in this file.
{{
	admin off
{tls}	servers {{
		max_header_size 16KB
		timeouts {{
			read_header {read_header}
			read_body {read_body}
			write {write}
			idle {idle}
		}}
	}}
}}

{address} {{
	# One JSON line per request. NO request headers (X-API-Key is one), no TLS details, no response headers.
	log {{
		output stdout
		format filter {{
			wrap json
			fields {{
				request>headers delete
				request>tls delete
				resp_headers delete
			}}
		}}
	}}
	log_append request_id {{http.request.uuid}}

	header {{
		-Server
		X-Content-Type-Options nosniff
		Cache-Control "no-store"
		Referrer-Policy no-referrer
	}}

	# The ONLY two things that get through. Exact, case-sensitive, on the decoded path.
	@ask expression `{{http.request.method}} == "POST" && {{http.request.uri.path}} == "/ask"`
	@health expression `({{http.request.method}} == "GET" || {{http.request.method}} == "HEAD") && {{http.request.uri.path}} == "/healthz"`

	handle @ask {{
		request_body {{
			max_size {max_body}
		}}
		request_header X-Request-ID {{http.request.uuid}}
		reverse_proxy {upstream} {{
			request_buffers 32KB
			header_down -Server
			transport http {{
				dial_timeout 5s
				response_header_timeout {upstream_wait}
			}}
		}}
	}}

	handle @health {{
		method GET
		request_header X-Request-ID {{http.request.uuid}}
		reverse_proxy {upstream} {{
			header_down -Server
			transport http {{
				dial_timeout 3s
				response_header_timeout 10s
			}}
		}}
	}}

	# Everything else. The API never sees it.
	handle {{
		respond "not found" 404
	}}

	# Errors the door itself produces (API down = 502, body too big = 413 ...): same headers, short plain text, no addresses.
	handle_errors {{
		header {{
			-Server
			X-Content-Type-Options nosniff
			Cache-Control "no-store"
		}}
		respond "{{http.error.status_text}}" {{http.error.status_code}}
	}}
}}
'''


def write_caddyfile(project_dir: str = ".", **kw) -> str:
    path = os.path.join(project_dir, "Caddyfile")
    if os.path.exists(path):
        shutil.copyfile(path, path + ".previous")
    with open(path, "w", encoding="utf-8", newline="\n") as f:          # Docker wants LF line endings
        f.write(caddyfile_text(**kw))
    return path


def main(argv: Optional[List[str]] = None) -> int:
    path = write_caddyfile(".")
    print("wrote", path)
    return 0


def _utf8_stdio():
    """Windows hands a program a pipe that only knows cp1252, which cannot print the marks used here: ask for UTF-8 instead."""
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")


if __name__ == "__main__":
    _utf8_stdio()
    raise SystemExit(main(sys.argv[1:]))
